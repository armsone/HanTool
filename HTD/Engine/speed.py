"""
HttpsDown "속도 측정" (간이·실효 측정, Python stdlib only). Started by the app as `engine.py speed` when the user
pressed '속도 측정'; never scheduled or run in the background.

Fixed public endpoints of Cloudflare's speed test service (documented in github.com/cloudflare/speedtest README):
  GET  https://speed.cloudflare.com/__down?bytes=N   (N dummy bytes; N=0 for the HTTP response time)
  POST https://speed.cloudflare.com/__up             (dummy generated bytes)
The request carries no address: the target is fixed here. No cookies, Referer, Authorization, user files or result
reporting endpoints. Request "context" (memory/stdin only): {"proxy": "http://user-tag:pass@127.0.0.1:port"} when the
app's "HTTPS 연결 도움" is on — then every byte goes through that helper (CONNECT tunnel); there is no direct fallback.

Bounds: whole test about 25 s, at most 24 MiB requested in total (latency ~0, download 1/4/8 MiB, upload
0.25/1/4 MiB ramps, stopping early when a sample is long enough or the time budget is spent), short per-I/O timeouts,
fixed-size reads, nothing is written to disk. Default TLS certificate/hostname verification is kept.

Rates are bytes actually transferred * 8 / monotonic elapsed / 1e6 (Mbps):
  download: from receiving the response headers until the last body byte (connection setup and request round trip
            excluded); a sample cut by the time budget counts only the bytes received, flagged partial.
  upload:   from the first body byte sent until the server's response arrived (includes one response round trip,
            so it is an effective rate); an upload the server did not confirm is never counted.
  HTTP response time: median of several request→response-header times of __down?bytes=0 on one kept-alive
            connection. This is not an ICMP ping.

Events: speedProgress {phase, message, liveMbps?, latencyMs?, downloadMbps?, uploadMbps?, bytesUsed}
        speedResult   {ok, complete, via, endpoint, latencyMs, downloadMbps, uploadMbps, ..., failure, failureCode}
"""

import base64
import http.client
import socket
import ssl
import statistics
import time
from urllib.parse import unquote, urlsplit

HOST = "speed.cloudflare.com"
PORT = 443
ENDPOINT_NAME = "Cloudflare"
MIB = 1024 * 1024
TOTAL_SECONDS = 25.0
BYTE_CAP = 24 * MIB
IO_TIMEOUT = 8.0
LATENCY_SAMPLES = 7
LATENCY_SECONDS = 4.0
DOWNLOAD_SECONDS = 11.0
DOWN_STEPS = (1 * MIB, 4 * MIB, 8 * MIB)
UP_STEPS = (256 * 1024, 1 * MIB, 4 * MIB)
SUFFICIENT_SAMPLE = 2.5
PARTIAL_MIN_SECONDS = 1.0
PARTIAL_MIN_BYTES = 128 * 1024
CHUNK = 64 * 1024
SMALL_BODY = 64 * 1024
PROGRESS_EVERY = 0.25
HEADERS = {"User-Agent": "HttpsDown-speedcheck", "Cache-Control": "no-store", "Pragma": "no-cache"}
_PAYLOAD = b"\x00" * CHUNK
FATAL_CODES = ("bad_proxy", "helper_refused", "tls_failed", "dns_failed", "connect_failed")


class SpeedError(Exception):
    def __init__(self, code, message):
        Exception.__init__(self, code)
        self.code = code
        self.message = message


class _Partial(Exception):
    def __init__(self, nbytes, seconds):
        Exception.__init__(self, "partial")
        self.nbytes = nbytes
        self.seconds = seconds


def mbps(nbytes, seconds):
    """Megabits per second from bytes actually transferred and a nonzero elapsed time; None when unknown."""
    if not nbytes or nbytes <= 0 or not seconds or seconds <= 0:
        return None
    return nbytes * 8.0 / seconds / 1e6


def _round(v, nd=2):
    return None if v is None else round(v, nd)


def direct_factory():
    return http.client.HTTPSConnection(HOST, PORT, timeout=IO_TIMEOUT, context=ssl.create_default_context())


def proxy_factory(proxy):
    """CONNECT tunnel through the app's loopback helper only. Anything else is refused (never a direct fallback)."""
    try:
        p = urlsplit(str(proxy))
        port = p.port
    except ValueError:
        port = None
        p = None
    if p is None or p.scheme != "http" or p.hostname != "127.0.0.1" or not port or not p.username or p.password is None:
        raise SpeedError("bad_proxy", "HTTPS 연결 도움 설정이 올바르지 않아 측정하지 않았습니다 (직접 연결로 바꾸지 않았습니다).")
    token = base64.b64encode(("%s:%s" % (unquote(p.username), unquote(p.password))).encode("utf-8")).decode("ascii")

    def make():
        c = http.client.HTTPSConnection("127.0.0.1", port, timeout=IO_TIMEOUT, context=ssl.create_default_context())
        c.set_tunnel(HOST, PORT, headers={"Proxy-Authorization": "Basic " + token})
        return c
    return make


def classify(exc):
    """(code, Korean message) for a failure. Never includes addresses, credentials or raw remote text."""
    if isinstance(exc, SpeedError):
        return exc.code, exc.message
    if isinstance(exc, ssl.SSLCertVerificationError):
        return "tls_failed", "측정 서버의 보안 인증서를 확인하지 못해 중단했습니다."
    if isinstance(exc, ssl.SSLError):
        return "tls_failed", "측정 서버와 보안 연결(TLS)을 맺지 못했습니다."
    if isinstance(exc, socket.timeout):
        return "timeout", "측정 서버 응답이 제시간(%d초)에 오지 않았습니다." % int(IO_TIMEOUT)
    if isinstance(exc, socket.gaierror):
        return "dns_failed", "측정 서버 이름(%s)을 찾지 못했습니다." % HOST
    if isinstance(exc, OSError) and "tunnel connection failed" in str(exc).lower():
        return "helper_refused", ("HTTPS 연결 도움이 측정 서버 연결을 열지 못했습니다 (직접 연결로 바꾸지 않았습니다).")
    if isinstance(exc, ConnectionRefusedError):
        return "connect_failed", "연결이 거부되었습니다."
    if isinstance(exc, http.client.IncompleteRead):
        return "truncated", "측정 서버 응답이 중간에 끊겨 결과를 쓰지 않았습니다."
    if isinstance(exc, (http.client.HTTPException, ValueError)):
        return "http_failed", "측정 서버 응답 형식이 예상과 달랐습니다."
    if isinstance(exc, OSError):
        return "connect_failed", "측정 서버와의 연결이 끊어졌거나 연결하지 못했습니다."
    return "failed", "측정 중 예기치 않은 오류가 발생했습니다."


class Meter:
    """One kept-alive HTTPS connection (reopened only when the server closes or a sample was cut)."""

    def __init__(self, factory, progress, total_seconds=TOTAL_SECONDS, byte_cap=BYTE_CAP, clock=time.monotonic):
        self.factory = factory
        self.progress = progress
        self.clock = clock
        self.start = clock()
        self.deadline = self.start + total_seconds
        self.byte_cap = byte_cap
        self.requested = 0   # bytes asked for (upper bound of what can be transferred)
        self.used = 0        # bytes actually received/sent
        self.conn = None
        self._last_emit = 0.0

    def left(self, until=None):
        end = self.deadline if until is None else min(until, self.deadline)
        return end - self.clock()

    def can_request(self, n):
        return self.requested + n <= self.byte_cap

    def close(self):
        if self.conn is not None:
            try:
                self.conn.close()
            except Exception:
                pass
        self.conn = None

    def _connection(self):
        if self.conn is None:
            c = self.factory()
            c.timeout = max(0.5, min(IO_TIMEOUT, self.left()))
            c.connect()
            self.conn = c
        self._io_timeout()
        return self.conn

    def _io_timeout(self, until=None):
        sock = getattr(self.conn, "sock", None)
        if sock is not None:
            sock.settimeout(max(0.5, min(IO_TIMEOUT, self.left(until) + 0.5)))

    def _check(self, resp, length=None):
        if resp.status != 200:
            if 300 <= resp.status < 400:
                raise SpeedError("unexpected_redirect", "측정 서버가 예상하지 않은 다른 주소로 보내려 해 따르지 않았습니다 (HTTP %d)." % resp.status)
            raise SpeedError("unexpected_status", "측정 서버가 예상과 다른 응답(HTTP %d)을 보냈습니다." % resp.status)
        enc = (resp.getheader("Content-Encoding") or "identity").strip().lower()
        if enc not in ("", "identity"):
            raise SpeedError("encoded", "측정 서버가 압축된 응답을 보내 실제 전송량을 셀 수 없습니다.")
        if length is not None:
            cl = resp.getheader("Content-Length")
            if cl is not None and cl.strip() != str(length):
                raise SpeedError("unexpected_length", "측정 서버가 요청과 다른 크기의 응답을 보냈습니다.")

    def _finish(self, resp):
        """Drain a small body (bounded); keep the connection only when the server allows it."""
        body = resp.read(SMALL_BODY + 1)
        if len(body) > SMALL_BODY or not resp.isclosed():
            self.close()
        elif resp.will_close:
            self.close()
        return body

    def _maybe_emit(self, phase, message, got, started):
        now = self.clock()
        if now - self._last_emit >= PROGRESS_EVERY:
            self._last_emit = now
            self.progress(phase, message, {"liveMbps": _round(mbps(got, now - started)), "bytesUsed": self.used})

    def latency_sample(self):
        conn = self._connection()
        t0 = self.clock()
        conn.request("GET", "/__down?bytes=0", headers=HEADERS)
        resp = conn.getresponse()
        t1 = self.clock()
        self._check(resp, 0)
        self.used += len(self._finish(resp))
        return (t1 - t0) * 1000.0

    def download_sample(self, n, until):
        conn = self._connection()
        self.requested += n
        conn.request("GET", "/__down?bytes=%d" % n, headers=HEADERS)
        resp = conn.getresponse()
        started = self.clock()
        self._check(resp, n)
        got = 0
        while got < n:
            if self.left(until) <= 0:
                self.close()
                raise _Partial(got, self.clock() - started)
            self._io_timeout(until)
            try:
                chunk = resp.read(min(CHUNK, n - got))
            except socket.timeout:
                if self.left(until) > 0.5:
                    raise
                self.close()   # the time budget, not the server, ended this read
                raise _Partial(got, self.clock() - started)
            if not chunk:
                break
            got += len(chunk)
            self.used += len(chunk)
            self._maybe_emit("download", "다운로드 측정 중...", got, started)
        elapsed = self.clock() - started
        if got != n:
            self.close()
            raise SpeedError("truncated", "측정 서버 응답이 중간에 끊겨 다운로드 결과를 쓰지 않았습니다.")
        if not resp.isclosed():
            self.close()
        elif resp.will_close:
            self.close()
        return got, elapsed

    def upload_sample(self, n, until):
        conn = self._connection()
        self.requested += n
        conn.putrequest("POST", "/__up")
        for k, v in HEADERS.items():
            conn.putheader(k, v)
        conn.putheader("Content-Type", "application/octet-stream")
        conn.putheader("Content-Length", str(n))
        conn.endheaders()
        started = self.clock()
        sent = 0
        while sent < n:
            if self.left(until) <= 0:
                self.close()
                raise SpeedError("time_budget", "시간 제한에 걸려 업로드를 끝까지 확인하지 못했습니다.")
            self._io_timeout(until)
            m = min(CHUNK, n - sent)
            conn.send(_PAYLOAD[:m])
            sent += m
            self.used += m
            self._maybe_emit("upload", "업로드 측정 중...", sent, started)
        resp = conn.getresponse()
        elapsed = self.clock() - started
        self._check(resp)
        self.used += len(self._finish(resp))
        return sent, elapsed


def _ramp(meter, steps, until, sample):
    """Runs growing samples until one is long enough, the next would not fit, or a budget is reached.
    Returns (best (bytes, seconds, partial) or None, failure (code, message) or None)."""
    best, failure = None, None
    for n in steps:
        left = meter.left(until)
        if left <= 0.5 or not meter.can_request(n):
            break
        if best is not None:
            rate = mbps(best[0], best[1]) or 0
            if rate > 0 and n * 8.0 / (rate * 1e6) > left:
                break
        try:
            got, secs = sample(n, until)
        except _Partial as p:
            if p.seconds >= PARTIAL_MIN_SECONDS and p.nbytes >= PARTIAL_MIN_BYTES and best is None:
                best = (p.nbytes, p.seconds, True)
            break
        except Exception as e:  # noqa: BLE001 - mapped to a fixed message
            meter.close()
            failure = classify(e)
            break
        if secs > 0:
            best = (got, secs, False)
        if secs >= SUFFICIENT_SAMPLE:
            break
    return best, failure


def measure(factory, progress, via, total_seconds=TOTAL_SECONDS, byte_cap=BYTE_CAP, clock=time.monotonic,
            down_steps=DOWN_STEPS, up_steps=UP_STEPS):
    """The whole bounded measurement. Returns the speedResult payload (unknown metrics stay None)."""
    m = Meter(factory, progress, total_seconds, byte_cap, clock)
    scale = total_seconds / TOTAL_SECONDS
    failures = []
    latency = []

    def fatal():
        # The path itself failed: later phases would only repeat it (and never switch to another path).
        return any(code in FATAL_CODES for code, _ in failures)

    progress("connect", "측정 서버(%s)에 연결하는 중..." % ENDPOINT_NAME, {"bytesUsed": 0})
    try:
        m._connection()
    except Exception as e:  # noqa: BLE001
        failures.append(classify(e))
        if failures[-1][0] not in FATAL_CODES:
            failures[-1] = ("connect_failed", failures[-1][1])

    if not fatal():
        progress("latency", "HTTP 응답 시간을 재는 중...", {"bytesUsed": m.used})
        lat_end = m.start + LATENCY_SECONDS * scale
        for _ in range(LATENCY_SAMPLES):
            if m.left(lat_end) <= 0:
                break
            try:
                latency.append(m.latency_sample())
            except Exception as e:  # noqa: BLE001
                m.close()
                failures.append(classify(e))
                break
        lat = statistics.median(latency) if latency else None
        progress("latency", "HTTP 응답 시간 측정 완료", {"latencyMs": _round(lat, 1), "bytesUsed": m.used})
    lat = statistics.median(latency) if latency else None

    down = up = None
    if not fatal():
        progress("download", "다운로드 측정 중...", {"bytesUsed": m.used})
        down, f = _ramp(m, down_steps, m.start + DOWNLOAD_SECONDS * scale, m.download_sample)
        if f:
            failures.append(f)
        progress("download", "다운로드 측정 완료", {"downloadMbps": _round(mbps(*down[:2])) if down else None,
                                               "bytesUsed": m.used})
    if not fatal():
        progress("upload", "업로드 측정 중...", {"bytesUsed": m.used})
        up, f = _ramp(m, up_steps, None, m.upload_sample)
        if f:
            failures.append(f)
        progress("upload", "업로드 측정 완료", {"uploadMbps": _round(mbps(*up[:2])) if up else None, "bytesUsed": m.used})
    m.close()

    down_rate = mbps(*down[:2]) if down else None
    up_rate = mbps(*up[:2]) if up else None
    measured = [v for v in (lat, down_rate, up_rate) if v is not None]
    if not failures:
        if down is None:
            failures.append(("time_budget", "시간·데이터 한도 안에서 다운로드를 측정하지 못했습니다."))
        elif up is None:
            failures.append(("time_budget", "시간·데이터 한도 안에서 업로드를 측정하지 못했습니다."))
    partial = bool(down and down[2]) or bool(up and up[2])
    return {
        "ok": bool(measured),
        "complete": lat is not None and down_rate is not None and up_rate is not None and not partial and not failures,
        "via": via, "endpoint": ENDPOINT_NAME, "host": HOST,
        "latencyMs": _round(lat, 1), "latencySamples": len(latency),
        "downloadMbps": _round(down_rate), "downloadBytes": down[0] if down else 0,
        "downloadPartial": bool(down and down[2]),
        "uploadMbps": _round(up_rate), "uploadBytes": up[0] if up else 0,
        "bytesUsed": m.used, "bytesRequested": m.requested, "byteCap": byte_cap,
        "seconds": round(m.clock() - m.start, 2),
        "failureCode": failures[0][0] if failures else None,
        "failure": failures[0][1] if failures else None,
    }


def run_speed(eng, job_id, generation, request):
    """Entry for `engine.py speed`. Exit status 0 = speedResult was reported (success or an honest failure)."""
    ctx = (request or {}).get("context") or {}
    proxy = ctx.get("proxy")

    def progress(phase, message, extra):
        payload = {"phase": phase, "message": message}
        payload.update({k: v for k, v in (extra or {}).items() if v is not None})
        eng.emit_event(job_id, generation, "speedProgress", payload)

    try:
        factory = proxy_factory(proxy) if proxy else direct_factory
    except SpeedError as e:
        eng.emit_event(job_id, generation, "speedResult", {
            "ok": False, "complete": False, "via": "helper", "endpoint": ENDPOINT_NAME, "host": HOST,
            "latencyMs": None, "downloadMbps": None, "uploadMbps": None, "bytesUsed": 0,
            "failureCode": e.code, "failure": e.message})
        return 0
    result = measure(factory, progress, "helper" if proxy else "direct")
    eng.emit_event(job_id, generation, "speedResult", result)
    return 0
